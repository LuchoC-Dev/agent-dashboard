// Wraps src/mocks/mock-data.json as docs/mockups/mock-data.js so the HTML
// mockups load the shared sample data from file:// (no fetch, no server).
// Run: npm run mockups:data
//
// Mockup-only enrichment: the shared sample data has a single version per model
// family. To preview how versions of a family are shown (same hue, darker shade
// per older version), the oldest sessions of each family are relabeled to earlier
// versions. Same shape as src/bindings; only model ids change (costs are kept).
import { readFileSync, writeFileSync } from "node:fs";

const data = JSON.parse(readFileSync("src/mocks/mock-data.json", "utf8"));

// family model id -> older ids, newest first; sessions are split evenly by start time
const OLDER = {
  "claude-opus-5-5": ["claude-opus-5-0", "claude-opus-4-8"],
  "claude-sonnet-5-5": ["claude-sonnet-5-0"],
};
for (const [current, older] of Object.entries(OLDER)) {
  const ss = data.sessions.filter((s) => s.models[0] === current).sort((a, b) => b.startedAt.localeCompare(a.startedAt));
  const per = Math.ceil(ss.length / (older.length + 1));
  ss.forEach((s, i) => {
    const id = [current, ...older][Math.floor(i / per)];
    if (id === current) return;
    const d = data.details[s.id];
    s.models = s.models.map((m) => (m === current ? id : m));
    d.summary = s;
    for (const m of d.messages) if (m.model === current) m.model = id;
  });
}
// Metrics/tool stats are recomputed per range by the mockup; only byModel would be stale.
data.metrics.byModel = [];

const out =
  "// Generated by scripts/gen-mockup-data.mjs from src/mocks/mock-data.json. Do not edit.\n" +
  "window.MOCK_DATA = " + JSON.stringify(data) + ";\n";
writeFileSync("docs/mockups/mock-data.js", out);
const models = [...new Set(data.sessions.flatMap((s) => s.models))].sort();
console.log(`docs/mockups/mock-data.js: ${data.sessions.length} sessions, models: ${models.join(", ")}`);
